CREATE TABLE users (
    id TEXT PRIMARY KEY,
    username TEXT COLLATE "C" NOT NULL,
    email TEXT COLLATE "C" NOT NULL,
    password_hash TEXT NOT NULL,
    verified INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE UNIQUE INDEX users_username_case_insensitive ON users (lower(username));
CREATE UNIQUE INDEX users_email_case_insensitive ON users (lower(email));

CREATE TABLE verification (
    user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    code_hash TEXT NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE recovery (
    user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    code_hash TEXT NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE credentials (
    user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    encrypted BYTEA NOT NULL
);

CREATE TABLE exchange_ownership (
    testnet INTEGER NOT NULL,
    exchange_user TEXT NOT NULL,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (testnet, exchange_user)
);

CREATE INDEX exchange_ownership_user ON exchange_ownership (user_id);

CREATE TABLE records (
    scope_id TEXT NOT NULL,
    namespace TEXT NOT NULL,
    key TEXT COLLATE "C" NOT NULL,
    value TEXT NOT NULL,
    updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    bot_id TEXT,
    audit_time TEXT COLLATE "C",
    PRIMARY KEY (scope_id, namespace, key)
);

CREATE INDEX records_bot_id ON records (scope_id, namespace, bot_id, key) WHERE bot_id IS NOT NULL;
CREATE INDEX records_audit_time ON records (scope_id, audit_time DESC NULLS LAST, key)
    WHERE namespace = 'audit_events';

CREATE TABLE position_owners (
    scope_id TEXT NOT NULL,
    account TEXT NOT NULL,
    position_id TEXT NOT NULL,
    bot_id TEXT NOT NULL,
    PRIMARY KEY (scope_id, account, position_id)
);

CREATE TABLE portfolio_snapshots (
    scope_id TEXT NOT NULL,
    captured_at TEXT COLLATE "C" NOT NULL,
    equity_usdt DOUBLE PRECISION NOT NULL,
    valuation_complete INTEGER NOT NULL,
    data TEXT NOT NULL,
    PRIMARY KEY (scope_id, captured_at)
);

CREATE TABLE portfolio_cashflows (
    scope_id TEXT NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    occurred_at TEXT COLLATE "C" NOT NULL,
    amount_usdt DOUBLE PRECISION NOT NULL,
    note TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (scope_id, id)
);

CREATE INDEX portfolio_cashflows_time ON portfolio_cashflows (scope_id, occurred_at, id);
